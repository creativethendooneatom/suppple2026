// Helper function to get article by title
export function getArticleByTitle(title: string) {
  return articleDatabase[title] || null;
}

// Helper function to search articles
export function searchArticles(query: string) {
  const results: any[] = [];
  const lowerQuery = query.toLowerCase();
  
  Object.values(articleDatabase).forEach(article => {
    if (
      article.title.toLowerCase().includes(lowerQuery) ||
      article.content.intro.toLowerCase().includes(lowerQuery) ||
      article.category.toLowerCase().includes(lowerQuery)
    ) {
      results.push(article);
    }
  });
  
  return results;
}
